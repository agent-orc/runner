#!/usr/bin/env python3
"""Generate the runner's static price seed from a pinned TokenEconomy snapshot."""

import argparse
import hashlib
import json
from datetime import datetime
from decimal import Decimal
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "pricing/model-prices.json"
MANIFEST = ROOT / "pricing/catalog-source.json"
TARGET = ROOT / "src/CodingAgentRunner/Pricing/ModelPriceSeed.cs"


def quoted(value):
    return json.dumps(value, ensure_ascii=True)


def money(value):
    return f"{Decimal(str(value)):f}m"


def instant(value):
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.utcoffset().total_seconds() != 0 or parsed.microsecond:
        raise ValueError(f"Unsupported price instant: {value}")
    return (f"new DateTime({parsed.year}, {parsed.month}, {parsed.day}, "
            f"{parsed.hour}, {parsed.minute}, {parsed.second}, DateTimeKind.Utc)")


def generate():
    raw = SOURCE.read_bytes()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    digest = hashlib.sha256(raw).hexdigest()
    if digest != manifest["sha256"]:
        raise ValueError("Pinned catalogue hash changed; update catalog-source.json and regenerate")
    listings = json.loads(raw, parse_float=Decimal)
    if not isinstance(listings, list):
        raise ValueError("Expected a catalogue array")

    lines = [
        "// <auto-generated> Generated by scripts/generate-model-price-seed.py. Do not edit. </auto-generated>",
        "namespace CodingAgentRunner.Pricing;",
        "",
        "/// <summary>Static price snapshot generated from the pinned TokenEconomy catalogue.</summary>",
        "internal static class ModelPriceSeed",
        "{",
        f"    internal const string SourceVersion = {quoted(manifest['catalogVersion'])};",
        f"    internal const string SourceSnapshotDate = {quoted(manifest['snapshotDate'])};",
        f"    internal const string SourceSha256 = {quoted(digest)};",
        "",
        "    internal static IReadOnlyList<ModelListing> Listings() =>",
        "    [",
    ]
    for listing in listings:
        lines += ["        new()", "        {", f"            ModelId = {quoted(listing['modelId'])},"]
        if listing.get("vendor") is not None:
            lines.append(f"            Vendor = {quoted(listing['vendor'])},")
        if listing.get("aliases"):
            lines.append("            Aliases = [" + ", ".join(map(quoted, listing["aliases"])) + "],")
        if listing.get("note") is not None:
            lines.append(f"            Note = {quoted(listing['note'])},")
        if listing.get("history"):
            lines.append("            History =")
            lines.append("            [")
            for price in listing["history"]:
                lines += [
                    "                new()",
                    "                {",
                    f"                    ValidFrom = {instant(price['validFrom'])},",
                    f"                    InputPerMTok = {money(price['inputPerMTok'])},",
                    f"                    OutputPerMTok = {money(price['outputPerMTok'])},",
                ]
                for key, property_name in (("cacheReadPerMTok", "CacheReadPerMTok"),
                                           ("cacheWritePerMTok", "CacheWritePerMTok")):
                    if price.get(key) is not None:
                        lines.append(f"                    {property_name} = {money(price[key])},")
                if price.get("longContextThreshold") is not None:
                    lines.append(f"                    LongContextThreshold = {price['longContextThreshold']},")
                if price.get("longContextRateMultiplier") is not None:
                    lines.append(f"                    LongContextRateMultiplier = {money(price['longContextRateMultiplier'])},")
                for key, property_name in (("currency", "Currency"),
                                           ("source", "Source"), ("note", "Note")):
                    if price.get(key) is not None:
                        lines.append(f"                    {property_name} = {quoted(price[key])},")
                if price.get("unconfirmed"):
                    lines.append("                    Unconfirmed = true,")
                lines += ["                },"]
            lines.append("            ],")
        lines += ["        },"]
    lines += ["    ];", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated seed differs")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != generated:
            parser.exit(1, "ModelPriceSeed.cs is stale; run scripts/generate-model-price-seed.py\n")
    else:
        TARGET.write_text(generated, encoding="utf-8")
